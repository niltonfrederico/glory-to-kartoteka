#!/usr/bin/env python3
"""Build theme.css: the generated token contract plus the hand-written component layer.

    python3 tools/build.py                 # sync tokens from ../glory-to-design if it is there, then bundle
    python3 tools/build.py --tokens PATH   # take the contract file from PATH instead
    python3 tools/build.py --no-sync       # bundle from the vendored tokens/tokens.obsidian.css as is
    python3 tools/build.py --showcase      # also refresh ../glory-to-design/showcase/obsidian.css (theme + snippets)
    python3 tools/build.py --check         # exit 1 when theme.css is not what the sources would produce

Layers:
  tokens/tokens.obsidian.css   vendored copy of glory-to-design's generated contract (never edit)
  src/theme.css                the component layer, hand-written, tokens only (edit this)
  theme.css                    the bundle Obsidian loads (generated here, committed)
  snippets/g2-*.css            one plugin each, installed as they are

Colours are born in glory-to-design/tools/derive_tokens.py. A hex anywhere in this repo
outside tokens/ is a bug.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "tokens" / "tokens.obsidian.css"
SRC = ROOT / "src" / "theme.css"
OUT = ROOT / "theme.css"
SIBLING = ROOT.parent / "glory-to-design"
SIBLING_TOKENS = SIBLING / "tokens" / "tokens.obsidian.css"
SIBLING_SHOWCASE = SIBLING / "showcase" / "obsidian.css"

HEAD = (
    "/* GENERATED by tools/build.py: tokens/tokens.obsidian.css (the contract emitted by\n"
    " * glory-to-design) followed by src/theme.css (the component layer). Edit those two;\n"
    " * this file is overwritten on the next build.\n"
    " * Install: tools/install.py, or copy theme.css + manifest.json into\n"
    " * <vault>/.obsidian/themes/Nirvytekh/ and the snippets into <vault>/.obsidian/snippets/. */\n\n"
)


def bundle() -> str:
    return HEAD + TOKENS.read_text() + "\n" + SRC.read_text()


def showcase_bundle(theme: str) -> str:
    snippets = sorted((ROOT / "snippets").glob("g2-*.css"))
    return theme + "".join(f"\n/* snippet: {p.name} */\n" + p.read_text() for p in snippets)


def hex_outside_tokens() -> list[str]:
    hits = []
    for p in [SRC, *sorted((ROOT / "snippets").glob("*.css"))]:
        for n, line in enumerate(p.read_text().splitlines(), 1):
            if re.search(r"#[0-9a-fA-F]{3,8}\b", line):
                hits.append(f"{p.relative_to(ROOT)}:{n}: {line.strip()}")
    return hits


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tokens", type=Path)
    ap.add_argument("--no-sync", action="store_true")
    ap.add_argument("--showcase", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    src = args.tokens or (None if args.no_sync else (SIBLING_TOKENS if SIBLING_TOKENS.exists() else None))
    if src and not args.check and src.resolve() != TOKENS.resolve():
        TOKENS.write_text(src.read_text())
        print(f"tokens  <- {src}")
    elif src is None and not TOKENS.exists():
        sys.exit("no tokens: pass --tokens PATH or put glory-to-design beside this repo")

    bad = hex_outside_tokens()
    if bad:
        print("hex outside tokens/:", *bad, sep="\n  ")
        return 1

    theme = bundle()
    if args.check:
        stale = not OUT.exists() or OUT.read_text() != theme
        print("theme.css", "STALE: run tools/build.py" if stale else "up to date")
        return 1 if stale else 0
    OUT.write_text(theme)
    print(f"theme.css  {len(theme):,} bytes")
    if args.showcase:
        if not SIBLING_SHOWCASE.parent.is_dir():
            sys.exit(f"no showcase dir at {SIBLING_SHOWCASE.parent}")
        SIBLING_SHOWCASE.write_text(showcase_bundle(theme))
        print(f"showcase   -> {SIBLING_SHOWCASE}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
